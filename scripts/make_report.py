"""Assemble report/draft.md from the generated tables (results/tables/*.md, tables.json) and figures.

Every number is inserted from generated files. Interpretive sentences are tagged [OBSERVATION] (directly
read off a table) or [HYPOTHESIS] (a possible explanation the experiments do not establish) for the
student to verify and rewrite.
  python scripts/make_report.py [--smoke]
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from src.pipeline import get_cfg  # noqa: E402
from src.utils import load_json, results_root  # noqa: E402

NAMES = {"ngram": "trigram", "rnn": "RNN", "lstm": "LSTM", "transformer": "Transformer"}


def table(tdir: Path, name: str) -> str:
    p = tdir / f"{name}.md"
    return p.read_text(encoding="utf-8") if p.exists() else f"*(table {name} not generated yet)*\n"


def ppl_of(r):
    v = r["test_ppl"]
    return v if isinstance(v, (int, float)) else v[0]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--smoke", action="store_true")
    args = ap.parse_args()
    cfg = get_cfg(args.smoke)
    root = results_root(cfg, args.smoke)
    tdir = root / "tables"
    T = load_json(tdir / "tables.json")
    fig = "figures" if not args.smoke else "results_smoke/figures"
    out = ROOT / "report" / ("draft_smoke.md" if args.smoke else "draft.md")
    L = []
    w = L.append
    w("# DSA4213 Assignment 1 — report draft (auto-generated)\n")
    if args.smoke:
        w("> **SMOKE RUN** — 1% data, 1 epoch. Numbers are meaningless; this file only checks the pipeline.\n")
    w("> Generated by `scripts/make_report.py` from `results/**/*.json`. Every interpretive sentence is tagged "
      "[OBSERVATION] or [HYPOTHESIS]; rewrite in your own words and delete the tags before submission.\n")

    w("## 0. Comparison question\n")
    w("*How do n-gram, RNN, LSTM and Transformer language models of matched size differ on WikiText-2, does "
      "fixing the input embeddings help the LSTM, and does better next-token prediction translate into better "
      "frozen features for topic classification?* (edit to taste)\n")

    ds = T["data"]
    w("## 1. Data and preprocessing\n")
    w(f"WikiText-2 (tokenized, `wikitext-2-v1`, official splits), lowercased, whitespace-split, empty lines "
      f"dropped, `<eos>` appended to every line; the dataset's `<unk>` is our single `<unk>`. Vocabulary = all "
      f"training types (V = {ds['vocab_size']}). Each split is one token stream cut into non-overlapping "
      f"128-token chunks (no state carried across chunks); the last chunk is padded and padded targets are "
      f"excluded from the loss. All four models score exactly the same "
      f"{ds['splits']['test']['targets']} test targets.\n")
    w(table(tdir, "data_stats"))

    p1 = T.get("part1", {})
    w("## 2. Part I — model families\n")
    w("Setup: neural models share embedding dim 100, hidden/d_model 256, 2 layers, dropout 0.3, untied output "
      "layer, context 128, AdamW (wd 0.01), clip 1.0, batch 32, AMP; LR per architecture from a 2-epoch sweep "
      "on validation; early stopping (patience 3) on validation loss; test evaluated once on the best checkpoint. "
      "Trigram: interpolated with λ chosen by grid search on validation.\n")
    w(table(tdir, "part1_main"))
    w(f"![Part I loss curves]({'../' + fig}/part1_loss_curves.png)\n")
    if p1:
        ranked = sorted(p1, key=lambda k: ppl_of(p1[k]))
        w("- [OBSERVATION] Test-perplexity ranking (best first): "
          + " < ".join(f"{NAMES[k]} ({ppl_of(p1[k]):.1f})" for k in ranked) + ".")
        neural = [k for k in ranked if k != "ngram"]
        if neural:
            w("- [OBSERVATION] Best epochs per seed: " + "; ".join(
                f"{NAMES[k]} {p1[k]['best_epoch']}" for k in neural) + ". Stopping reasons: " + "; ".join(
                f"{NAMES[k]} {p1[k]['stopped']}" for k in neural) + ".")
        if "lstm" in p1 and "transformer" in p1:
            (ml, sl, _), (mt, st, _) = p1["lstm"]["test_ppl"], p1["transformer"]["test_ppl"]
            better = "LSTM" if ml < mt else "Transformer"
            if abs(ml - mt) < max(sl, st):
                w(f"- [OBSERVATION] LSTM ({ml:.2f} ± {sl:.2f}) and Transformer ({mt:.2f} ± {st:.2f}) differ by "
                  f"{abs(ml - mt):.2f} ppl, less than the seed-to-seed std: treat them as tied on test perplexity.")
            else:
                w(f"- [OBSERVATION] Between the LSTM and the Transformer, the {better} reaches the lower test perplexity.")
        for k in neural:
            if all(r == "max_epochs" for r in p1[k]["stopped"]):
                w(f"- [OBSERVATION] {NAMES[k]}: every seed hit the {T.get('max_epochs', 'maximum')}-epoch limit with "
                  f"its best epoch at or near the end ({p1[k]['best_epoch']}), i.e. it was still improving; its "
                  "result is limited by the training budget, not converged.")
        w("- [HYPOTHESIS] Differences between neural models may reflect inductive bias (recurrence vs attention), "
          "the small data size (2M tokens) favouring the more constrained model, the fixed 128-token context, or "
          "per-architecture LR/epoch budget; these runs do not separate these factors.")
        w("- [HYPOTHESIS] The output layer (256×V) dominates the parameter count of every neural model, so total "
          "parameters say little about the capacity of the sequence core.")
        w("- [OBSERVATION] Fill in: overfitting signs (train loss keeps falling while val loss rises after the best "
          "epoch) per model, from the loss-curve figure.\n")
    w("### Generated text\n")
    w(table(tdir, "generation_metrics"))
    gp = root / "part1" / "generations.json"
    if gp.exists():
        g = load_json(gp)
        w("Example continuations (prompt 1, greedy and sampled), seed-0 models:\n")
        for name, m in g["models"].items():
            for s in g["settings"]:
                c = m[s]["continuations"][0]
                w(f"- **{NAMES.get(name, name)} / {s}**: *{c['prompt']}* → {c['text']}")
        w("")
    w("- [OBSERVATION] Fill in: concrete repetition / fluency / consistency differences (see "
      "`results/part1/generations.json` and the repeated-trigram rates above).\n")

    p2 = T.get("part2", {})
    w("## 3. Part II — embedding ablation (LSTM)\n")
    w("Identical LSTM configuration, LR and seeds; only the input-embedding block differs. Own embeddings: gensim "
      "skip-gram (dim 100, window 5, min_count 1, negative 10, 10 epochs) on the training split only. Public: "
      "GloVe 6B 100d. Frozen tables: the entire table is fixed (`from_pretrained(freeze=True)`); missing words: "
      "`<pad>` = 0, `<unk>` = mean of covered vectors (if missing), others ~ N(0, σ²) with σ = std of covered "
      "vectors, fixed seed. Non-embedding initialisation is identical across variants for a given seed.\n")
    w(table(tdir, "part2_embeddings"))
    w(f"![Part II loss curves]({'../' + fig}/part2_loss_curves.png)\n")
    if p2:
        ranked = sorted(p2, key=lambda k: p2[k]["test_ppl"][0])
        w("- [OBSERVATION] Test-perplexity ranking: " + " < ".join(f"{k} ({p2[k]['test_ppl'][0]:.1f})" for k in ranked) + ".")
        w("- [HYPOTHESIS] Frozen tables remove ~V×100 trainable parameters, which may reduce overfitting but also "
          "prevents adapting vectors to next-word prediction; GloVe additionally carries information from ~6B tokens "
          "of Wikipedia+Gigaword (and may overlap WikiText test text), so a GloVe advantage is not purely an "
          "architectural effect.")
        w("- [OBSERVATION] Fill in: convergence speed (best epoch) and stability (seed variance, spikes) differences.\n")

    p3 = T.get("part3")
    w("## 4. Part III — downstream classification (AG News)\n")
    w("Frozen LMs (main comparison on the seed-0 checkpoints, repeated with the same protocol on the seed-1 and "
      "seed-2 checkpoints); each article (converted to WikiText conventions, truncated to 128 tokens) is encoded and "
      "the last-layer states are mean-pooled over non-pad positions (main comparison: LSTM vs Transformer). "
      "Classifier: StandardScaler + logistic regression, C chosen on validation accuracy, fitted on the 8k train "
      "set, test evaluated once.\n")
    w(table(tdir, "part3_oov"))
    w(table(tdir, "part3_downstream"))
    w(table(tdir, "part3_rank"))
    if (tdir / "part3_seeds.md").exists():
        w("### Part III over LM seeds\n")
        w(table(tdir, "part3_seeds"))
        w(table(tdir, "part3_pairwise"))
        w(table(tdir, "part3_rank_seeds"))
        w(f"![LM ppl vs accuracy]({'../' + fig}/part3_ppl_vs_acc.png)\n")
    w(f"![Confusion matrices]({'../' + fig}/part3_confusion.png)\n")
    if p3:
        r = p3["representations"]
        if "lstm_mean" in r and "transformer_mean" in r:
            a, b = r["lstm_mean"]["test_acc"], r["transformer_mean"]["test_acc"]
            w(f"- [OBSERVATION] LSTM mean-pooled features: test accuracy {a:.4f}; Transformer: {b:.4f}.")
        pc = p3["pairwise_counts"]
        w(f"- [OBSERVATION] Test articles where only the LSTM is right: {pc.get('lstm_right_transformer_wrong')}; "
          f"only the Transformer: {pc.get('transformer_right_lstm_wrong')}; both wrong: {pc.get('both_wrong')} "
          "(examples in `results/part3/errors.json`).")
        pw = p3.get("pairwise_lstm_vs_transformer")
        if pw:
            diffs = ", ".join(f"{x['diff']:+.4f}" for x in pw)
            pmax = max(x["mcnemar_exact_p"] for x in pw)
            agg = p3["aggregate"]
            w(f"- [OBSERVATION] Over LM seeds {p3['seeds']}: LSTM {agg['lstm_mean']['test_acc'][0]:.4f} ± "
              f"{agg['lstm_mean']['test_acc'][1]:.4f}, Transformer {agg['transformer_mean']['test_acc'][0]:.4f} ± "
              f"{agg['transformer_mean']['test_acc'][1]:.4f}; Transformer − LSTM per seed: {diffs}; exact McNemar "
              f"p ≤ {pmax:.1e} for every seed. The gap is consistent across checkpoints, not a single-seed effect.")
            w("- [OBSERVATION] Rank agreement (seed means, table above): compare the ppl rank with the downstream "
              "rank; LSTM and Transformer perplexities are within one std of each other.")
        w("- [HYPOTHESIS] Whether the LM-perplexity ranking matches the downstream ranking (table above) may depend on "
          "the domain shift WikiText → news and on what mean pooling keeps from each model's states.\n")

    w("## 5. Cross-part discussion, limitations, lessons\n")
    w("- Limitations: single small corpus (2M tokens); one LR sweep of 2 epochs per architecture; laptop GPU timing "
      "(thermal throttling possible); GloVe trained on Wikipedia 2014 + Gigaword may overlap WikiText test text; "
      "Part III uses frozen features and a linear classifier only; generated text from seed-0 checkpoints only; "
      "LRs chosen by a 2-epoch sweep (favours fast early progress); models that hit the epoch limit are not "
      "converged.\n")
    w("## Reproducibility\n")
    w("See README.md (commands, configs, seeds, hardware, runtimes).\n")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
